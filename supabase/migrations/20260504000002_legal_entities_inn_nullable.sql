-- ============================================================
-- legal_entities.inn → nullable
-- ============================================================
-- Часть организаций из протоколов собраний (Технический заказчик-ЮГ,
-- Арбат Отель Менеджмент, Семейные курорты, Монолит) попадают в БД
-- из contacts_importer.py до того, как известны их реквизиты (ИНН/КПП/ОГРН).
--
-- Делаем inn nullable. Уникальность сохраняем — Postgres трактует множественные
-- NULL как разные значения, поэтому несколько строк без ИНН не нарушат constraint.
-- ИНН заполнятся позже (при загрузке первого договора с этой организацией или вручную).

alter table legal_entities alter column inn drop not null;

comment on column legal_entities.inn is
    'ИНН — уникальный бизнес-ключ. Может быть NULL для организаций, известных только по названию (например, из протоколов до загрузки договора).';

notify pgrst, 'reload schema';
