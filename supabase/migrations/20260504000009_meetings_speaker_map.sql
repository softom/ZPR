-- ============================================================
-- meetings.speaker_map — соответствие спикеров транскрипции участникам
-- ============================================================
-- Транскрипции из Телемоста / Zoom часто называют участников «Speaker 1»,
-- «Speaker 2» и т.п. LLM ошибочно атрибутирует реплики, поэтому добавляем
-- ручной маппинг: пользователь до запуска LLM сопоставляет каждого
-- неизвестного спикера с реальным участником из meeting_participants.
--
-- Формат:
-- {
--   "Speaker 1":   {"contact_id": "uuid", "label": "Антипов Артемий Юрьевич", "org": "ООО «Технический заказчик-ЮГ»"},
--   "Speaker 2":   {"contact_id": null,    "label": "Гость / без атрибуции",   "org": null},
--   "Иван Иванов": {"contact_id": "uuid", "label": "...", "org": "..."}
-- }

alter table meetings
    add column if not exists speaker_map jsonb not null default '{}'::jsonb;

comment on column meetings.speaker_map is
    'Соответствие raw-имён спикеров (как в файле транскрипции) реальным участникам. Применяется при чтении CSV перед отправкой в LLM.';

notify pgrst, 'reload schema';
