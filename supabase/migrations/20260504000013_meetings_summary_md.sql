-- ============================================================
-- meetings.summary_md — резюме собрания в MD-формате
-- ============================================================
-- Резюме формируется LLM по утверждённому протоколу (Секция 10
-- карточки собрания), затем правится пользователем и хранится
-- в БД. Скачивается в .docx через render?format=summary-docx.

alter table meetings add column if not exists summary_md text;

comment on column meetings.summary_md is
  'Резюме собрания в MD-формате (Ключевые решения / Обсудили / Выполнили / Решили). NULL = не сформировано.';

notify pgrst, 'reload schema';
