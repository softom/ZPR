-- Описательное поле объекта для LLM-промпта.
-- Не выводится в финальный отчёт. Используется как «приоритетный контекст
-- от владельца» для генерации разделов отчёта по объекту, особенно когда
-- автоматических данных (событий/задач/тем) недостаточно.

alter table objects add column if not exists llm_hint text;

comment on column objects.llm_hint is
    'Описательный контекст для LLM-промпта (не выводится в отчёт). Заполняется владельцем объекта когда автоматических данных мало.';

notify pgrst, 'reload schema';
