-- ============================================================================
-- Сохранение оригинального заголовка задачи MS Project до нормализации.
-- ============================================================================
-- Контекст: при импорте мы вырезаем из title упоминания объекта, который
-- и так привязан через object_ids. Чистый title попадает в БД, при экспорте
-- к нему добавляется утверждённый шифр (code объекта). title_original — для
-- аудита и round-trip без потерь.
-- ============================================================================

alter table calendar_entries
    add column title_original text;

comment on column calendar_entries.title_original is
    'Исходный <Name> задачи из MSPDI до нормализации (удаление вшитых названий объекта). Используется для аудита.';

notify pgrst, 'reload schema';
