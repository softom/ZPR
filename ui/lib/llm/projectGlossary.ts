// Глоссарий проектных терминов и аббревиатур.
// Подставляется в начало каждого LLM-промпта — чтобы модель не путалась
// в специфической терминологии (например ФЗ → Функциональное задание,
// а не Федеральный закон).
//
// Дополнять по мере появления неоднозначных терминов.
// Все промпты в `lib/reports/*` и `lib/protocol/*` импортируют PROJECT_GLOSSARY
// и подставляют его рядом с системными инструкциями.

export const PROJECT_GLOSSARY = `
═══════════════════════════════════════════════════
ГЛОССАРИЙ ПРОЕКТА (ОБЯЗАТЕЛЬНО К ИСПОЛЬЗОВАНИЮ)
═══════════════════════════════════════════════════
- **ФЗ** = **Функциональное задание** (НЕ «Федеральный закон»!). Это документ-задание
  на проектирование от заказчика подрядчику. Когда видишь сокращение «ФЗ» в нашем
  контексте — это всегда «Функциональное задание».
- **ТЭП** = Технико-экономические показатели (расчёты по проекту).
- **АГК** = Архитектурно-градостроительная концепция (первый этап договора).
- **ОПР** = Объёмно-планировочные решения (этап проектирования).
- **МОП** = Места общего пользования.
- **ГАП** = Главный архитектор проекта (роль / должность).
- **ТЗ-ЮГ** = ООО «Технический заказчик-ЮГ» (компания-технический заказчик).
- **ППТ** = Проект планировки территории (градостроительный документ).
- **ДПТ** = Документация по планировке территории.
- **ИРД** = Исходно-разрешительная документация.
- **ИД** = Исходные данные (для проектирования).
═══════════════════════════════════════════════════
`.trim()
