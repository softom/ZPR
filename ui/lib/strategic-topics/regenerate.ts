/**
 * LLM-перегенерация одного поля стратегической темы.
 * Используется кнопкой ✨ в карточке /strategic-topics/[id].
 *
 * Принимает текущее состояние темы + код поля + до 3 «эталонных» примеров
 * этого же поля из других недавно сохранённых тем. Примеры задают
 * целевую плотность и стиль — это снижает воду и расфокусировку.
 */

import { callPolzaJson } from '@/lib/llm/polza'

export const REGEN_FIELDS = [
  'title',
  'synopsis',
  'threats',
  'solutions',
  'deadlines',
] as const

export type RegenField = typeof REGEN_FIELDS[number]

const FIELD_LABEL: Record<RegenField, string> = {
  title:       'Название',
  synopsis:    'Синопсис',
  threats:     'Угрозы',
  solutions:   'Решения',
  deadlines:   'Сроки и контрольные точки',
}

// Минимальная длина поля для попадания в few-shot набор примеров.
// Слишком короткие — не показывают, как выглядит «полноценное» поле.
export const MIN_EXAMPLE_LENGTH: Record<RegenField, number> = {
  title:        15,
  synopsis:    150,
  threats:     150,
  solutions:   150,
  deadlines:    25,
}

const FIELD_GUIDE: Record<RegenField, string> = {
  title:
`Действие или предмет, до ~70 символов. Без вводных «Вопрос о…», без угроз,
без оценочности. Это ярлык-узнавание в списке.`,

  synopsis:
`1–4 предложения. Что происходит на эту тему, как сложилось, почему важно
сейчас. Это единственное описательное поле темы — должно давать читателю
полное понимание ситуации без необходимости ходить в источник.
Конкретика: числа, даты, участники (объекты, подрядчики, документы), стадии.
БЕЗ слов «важно», «ключевой», «является», «представляет собой», «играет роль».
БЕЗ предложений «надо», «следует», «необходимо» — действия живут в «Решениях».`,

  threats:
`3–5 предложений ИЛИ маркированный список через «- » (выбирай по логике
контекста, как в примерах). Будущее время. Что конкретно сорвётся, на каком
этапе, каков масштаб. БЕЗ «может негативно повлиять», «создаст риски» —
говори, какие именно сроки/объекты/документы пострадают.`,

  solutions:
`3–5 предложений ИЛИ маркированный список. Что делать. Уровень намерения.
БЕЗ дат и фамилий — это уровень задач, не темы.
БЕЗ «организовать систематическую работу», «обеспечить надлежащий уровень» —
говори, какой процесс/договор/документ создать.`,

  deadlines:
`Лаконично. Окно дат или контрольная точка с датой/этапом.
Например: «Окно работ: окт.2026 — авг.2027», «Критическая точка — вход в Концепцию (окт-ноя 2026)».
БЕЗ описаний рисков и решений.`,
}

const CATEGORY_LABEL: Record<string, string> = {
  environment:  'Средовое проектирование',
  engineering:  'Инженерное',
  land_legal:   'Земельно-правовое',
  organization: 'Организационное',
  personnel:    'Кадровое',
  contracting:  'Договорное',
}

export interface TopicSnapshot {
  title: string
  category: string
  synopsis: string
  threats: string
  solutions: string | null
  deadlines: string | null
  source_quote: string | null
  notes: string | null
}

export interface FieldExample {
  topic_title: string
  category: string
  field_value: string
}

// Признак, что в поле — заглушка из createNew (или вообще пусто):
// «— заполните синопсис —», «— заполните описание контекста —», «— заполните угрозы —».
function isPlaceholder(v: string | null | undefined): boolean {
  if (!v) return true
  const trimmed = v.trim()
  if (trimmed.length === 0) return true
  return /^—\s*заполните\s+/i.test(trimmed)
}

export async function regenerateTopicField(
  topic: TopicSnapshot,
  field: RegenField,
  examples: FieldExample[] = [],
): Promise<string> {
  const fieldLabel = FIELD_LABEL[field]
  const categoryLabel = CATEGORY_LABEL[topic.category] ?? topic.category
  const currentValue = (topic[field] ?? '').toString()
  const hasContent = !isPlaceholder(currentValue)

  // Два режима работы — определяет poведение LLM полностью.
  // Длина текущего значения в режиме полировки — для жёстких рамок длины.
  const currentLen = currentValue.length
  const maxLen = Math.ceil(currentLen * 1.2)
  // Структура — список или проза. Считаем «список» если ≥2 строк начинаются с «- ».
  const listLines = currentValue.split('\n').filter(l => /^\s*[-•*]\s/.test(l)).length
  const isList = listLines >= 2

  const modeBlock = hasContent
    ? `РЕЖИМ: ПОЛИРОВКА (refine).
В поле уже есть содержательный текст пользователя. Это ИСТОЧНИК ИСТИНЫ.
Твоя задача — отшлифовать стиль, сжать многословие, привести формулировки
к правилам, СОХРАНИВ все факты и СТРУКТУРУ исходного текста.

═══ АБСОЛЮТНЫЕ ПРАВИЛА (нарушение = провал задачи) ═══

1. ДЛИНА: текущая длина — ${currentLen} символов. Твой ответ — НЕ ДЛИННЕЕ ${maxLen}
   символов (это +20%). Лучше короче. Если короче на 30% — отлично.

2. СТРУКТУРА: ${isList
     ? `исходный текст — МАРКИРОВАННЫЙ СПИСОК из ${listLines} пунктов через «- ».
   Ответ ОБЯЗАН быть таким же списком. Не объединяй пункты в прозу.
   Не переставляй порядок пунктов. Можно слегка переформулировать каждый пункт,
   но не сливать их.`
     : `исходный текст — связная проза (${currentValue.split('\n\n').length} абзац(ев)).
   Ответ ОБЯЗАН быть прозой того же объёма абзацев. Не превращай в список.`}

3. ФАКТЫ: все числа, даты, названия (объектов, договоров, подрядчиков, этапов,
   документов, окон дат) из исходного текста — на месте. Не добавляй новых
   фактов из других полей темы.

4. ИНСТРУКЦИЯ к полю (ниже) — применяется ТОЛЬКО к стилю формулировок (запреты
   слов, тон). Указания о длине/структуре из неё ИГНОРИРУЙ — у тебя есть
   жёсткие правила выше.

5. Если исходный текст уже краток и хорош — верни его почти без изменений.`
    : `РЕЖИМ: ГЕНЕРАЦИЯ (draft from context).
Поле пустое или содержит шаблонный плейсхолдер. Сгенерируй содержательный
текст из других полей темы и цитаты-источника.
Соблюдай правила длины и структуры из инструкции к полю.
Равняйся на образцы из примеров (если есть).
Не выдумывай факты, которых нет в контексте.`

  const systemPrompt = `Ты — помощник руководителя строительного проекта «Золотые пески России» (8 курортных отелей в разных стадиях проектирования).

Переписываешь ОДНО поле стратегической управленческой темы.
Стратегическая тема — управленческое направление с горизонтом 6–18 месяцев. Не задача и не событие.

${modeBlock}

ОБЯЗАТЕЛЬНЫЕ правила стиля (для обоих режимов):
1. Деловой нейтральный тон. Никаких вводных и общих фраз.
2. Запрещены слова-паразиты управленческого жаргона:
   «является», «представляет собой», «обеспечение надлежащего», «играет ключевую роль»,
   «комплексный характер», «системный подход», «эффективное взаимодействие»,
   «оптимизация процессов», «обеспечить высокое качество», «приоритетной задачей является».
3. Конкретика > обобщения. Не размывай конкретные имена/цифры/даты в общие фразы.
4. Не дублируй другие поля темы. У каждого поля своя функция.

Если для поля показаны ПРИМЕРЫ из других тем — равняйся на их плотность и
структуру. Не копируй формулировки — заимствуй стиль.`

  const examplesBlock = examples.length > 0
    ? `\n═══════════════════════════════════════════════════
ПРИМЕРЫ — как выглядят поля «${fieldLabel}» в других темах
═══════════════════════════════════════════════════
${examples.map((ex, i) => (
  `Пример ${i + 1} (тема: «${ex.topic_title}», категория: ${CATEGORY_LABEL[ex.category] ?? ex.category}):
${ex.field_value}`
)).join('\n\n──────\n\n')}
`
    : ''

  // Главный блок — текущее значение поля. Идёт первым, выделено визуально.
  const currentValueBlock = hasContent
    ? `╔═══════════════════════════════════════════════════╗
║ ТЕКУЩИЙ ТЕКСТ ПОЛЯ «${fieldLabel}» — ИСТОЧНИК ИСТИНЫ ║
╚═══════════════════════════════════════════════════╝
${currentValue}
`
    : `╔═══════════════════════════════════════════════════╗
║ ПОЛЕ «${fieldLabel}» ПУСТО / ПЛЕЙСХОЛДЕР           ║
╚═══════════════════════════════════════════════════╝
${currentValue || '(пусто)'}
`

  // Контекст — остальные поля темы (без текущего, чтобы не путать LLM).
  const contextLines: string[] = [`Категория темы: ${categoryLabel}`]
  if (field !== 'title')     contextLines.push(`Название: ${topic.title || '—'}`)
  if (field !== 'synopsis')  contextLines.push(`Синопсис: ${topic.synopsis || '—'}`)
  if (field !== 'threats')   contextLines.push(`Угрозы: ${topic.threats || '—'}`)
  if (field !== 'solutions') contextLines.push(`Решения: ${topic.solutions || '—'}`)
  if (field !== 'deadlines') contextLines.push(`Сроки: ${topic.deadlines || '—'}`)
  if (topic.source_quote) contextLines.push(`\nИСТОЧНИК (текст раздела аналитического отчёта):\n${topic.source_quote}`)
  if (topic.notes)        contextLines.push(`Заметки оператора: ${topic.notes}`)

  const userPrompt = `${currentValueBlock}
═══════════════════════════════════════════════════
КОНТЕКСТ ТЕМЫ (другие поля — НЕ переноси сюда их содержимое целиком)
═══════════════════════════════════════════════════
${contextLines.join('\n')}
${examplesBlock}
═══════════════════════════════════════════════════
ИНСТРУКЦИЯ ДЛЯ ПОЛЯ «${fieldLabel}»
═══════════════════════════════════════════════════
${FIELD_GUIDE[field]}

ВЕРНИ СТРОГО JSON:
{"value": "новый текст поля без markdown-обёртки"}

Никаких \`\`\`, никаких пояснений. Только JSON.`

  const result = await callPolzaJson<{ value?: unknown }>(
    systemPrompt,
    userPrompt,
    { temperature: hasContent ? 0.2 : 0.3, max_tokens: 1500 },
  )

  const value = typeof result.value === 'string' ? result.value.trim() : ''
  if (!value) throw new Error('LLM вернул пустое значение')
  return value
}
